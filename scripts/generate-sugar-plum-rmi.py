#!/usr/bin/env python3
"""Generate an original, non-Midisoft RIFF MIDI demo from a public-domain theme.

Not a byte-for-byte copy or a transcription of any Microsoft/Windows RMI file.
Stdlib only, deterministic output (SMF format 1, 2/4 meter, RIFF RMID data).
"""
import argparse
import pathlib
import struct

TPQ = 240
BPM = 60
BAR = 2 * TPQ
# Pitch sequence simplified from Tchaikovsky's public-domain 1892 composition.
# Water supplies its own instrumentation, voice leading, phrasing, and timing.
# Celesta uses GM program 8 (zero-based). Pizzicato strings is GM 45.
BARS = [
    (79, 76, 79, 78), (75, 76, 74, 74), (74, 73, 73, 73), (72, 72, 72, 71),
    (76, 72, 76, 71), (76, 74, 72, 71), (70, 79, 76, 79), (78, 72, 71, 67),
    (67, 76, 67, 76), (78, 75, 76, 74), (74, 74, 73, 73), (72, 72, 71, 71),
    (76, 73, 76, 75), (71, 74, 71, 74), (72, 76, 72, 76), (75, 71, 78, 76),
]
OUTPUT = pathlib.Path(__file__).resolve().parents[1] / 'media' / 'win9x' / 'Dance of the Sugar-Plum Fairy (Water).rmi'


def varlen(value):
    if not 0 <= value <= 0x0FFFFFFF:
        raise ValueError(value)
    data = [value & 0x7F]
    value >>= 7
    while value:
        data.insert(0, 0x80 | (value & 0x7F))
        value >>= 7
    return bytes(data)


def meta(kind, payload):
    return bytes((0xFF, kind)) + varlen(len(payload)) + payload


def track(events):
    """Events are (absolute tick, priority, raw MIDI bytes); stable sorting."""
    last = 0
    out = bytearray()
    for tick, _, command in sorted(events, key=lambda item: (item[0], item[1])):
        if tick < last:
            raise ValueError('out-of-order MIDI event')
        out.extend(varlen(tick - last))
        out.extend(command)
        last = tick
    out.extend(b'\x00\xff\x2f\x00')
    return b'MTrk' + struct.pack('>I', len(out)) + out


def note(events, start, ticks, channel, pitch, velocity):
    events.append((start, 2, bytes((0x90 | channel, pitch, velocity))))
    events.append((start + ticks, 1, bytes((0x80 | channel, pitch, 0))))


def make_midi():
    title = b'Dance of the Sugar-Plum Fairy - Water edition (not Windows/Midisoft source)'
    attribution = b'1892 public-domain music by P. I. Tchaikovsky; new Water demonstration arrangement, 2026'
    control = [
        (0, 0, meta(0x03, title)),
        (0, 0, meta(0x02, attribution)),
        (0, 0, meta(0x51, (60_000_000 // BPM).to_bytes(3, 'big'))),
        (0, 0, meta(0x58, bytes((2, 2, 24, 8)))),
        (0, 0, meta(0x59, bytes((1, 1)))),
    ]
    celesta = [(0, 0, bytes((0xC0, 8))), (0, 0, bytes((0xB0, 7, 92)))]
    pizz = [(0, 0, bytes((0xC1, 45))), (0, 0, bytes((0xB1, 7, 70)))]
    bass = [(0, 0, bytes((0xC2, 32))), (0, 0, bytes((0xB2, 7, 66)))]
    for n in range(48):
        begin = n * BAR
        phrase = BARS[n % len(BARS)]
        for i, pitch in enumerate(phrase):
            note(celesta, begin + i * (TPQ // 2), TPQ // 2 - 12, 0,
                 pitch + (12 if n >= 32 and n % 8 == 7 else 0), 76 if i == 0 else 62)
        # A new sparse accompaniment, not a copy of the Windows sample sequence.
        root = (40, 43, 38, 40)[(n // 4) % 4]
        note(pizz, begin, TPQ - 24, 1, root + 12, 38)
        note(pizz, begin + TPQ, TPQ - 24, 1, root + 19, 34)
        note(bass, begin, TPQ // 2, 2, root, 50)
        note(bass, begin + TPQ, TPQ // 2, 2, root + 7, 44)
    midi = b'MThd' + struct.pack('>IHHH', 6, 1, 4, TPQ)
    midi += b''.join(map(track, (control, celesta, pizz, bass)))
    return midi


def make_rmi():
    midi = make_midi()
    # RIFF data chunks are padded to an even byte boundary; size excludes pad.
    data = b'data' + struct.pack('<I', len(midi)) + midi + (b'\0' if len(midi) & 1 else b'')
    return b'RIFF' + struct.pack('<I', 4 + len(data)) + b'RMID' + data


def verify(data):
    assert data[:4] == b'RIFF' and data[8:12] == b'RMID'
    assert struct.unpack('<I', data[4:8])[0] == len(data) - 8
    assert data[12:16] == b'data'
    size = struct.unpack('<I', data[16:20])[0]
    assert data[20:20+size].startswith(b'MThd')
    assert (size + 1) // 2 * 2 + 20 == len(data)
    midi = data[20:20+size]
    assert midi[:4] == b'MThd' and struct.unpack('>HHH', midi[8:14]) == (1, 4, TPQ)
    pos = 14
    for _ in range(4):
        assert midi[pos:pos+4] == b'MTrk'
        length = struct.unpack('>I', midi[pos+4:pos+8])[0]
        assert midi[pos+8+length-4:pos+8+length] == b'\x00\xff\x2f\x00'
        pos += 8 + length
    assert pos == len(midi)


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--check', action='store_true', help='Compare existing file with regenerated bytes')
    args = cli.parse_args()
    data = make_rmi()
    verify(data)
    if args.check:
        if OUTPUT.read_bytes() != data:
            raise SystemExit('RMID file is not in sync with generator')
        print('RMID byte-for-byte regeneration: OK')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(data)
        print(f'Wrote {OUTPUT}: {len(data)} bytes')


if __name__ == '__main__':
    main()
